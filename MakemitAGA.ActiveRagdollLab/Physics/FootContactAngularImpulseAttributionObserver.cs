        internal void CapturePreSolve(
            bool traceEnabled,
            int fixedSequence,
            float fixedDeltaTime,
            bool exactAuthorizedContact,
            Rigidbody footBody,
            Collider footCollider,
            Vector3 angularTransportTorqueWorld,
            Vector3 anklePdTorqueWorld,
            Vector3 supportAngularTorqueWorld,
            FootSoleProbeSnapshot probeSnapshot,
            FootAnkleFoundationReport report)
        {
            if (!traceEnabled || !exactAuthorizedContact || footBody == null || footBody.isKinematic)
            {
                _pending = false;
                CopyToReport(report, false);
                return;
            }

            if (_pending)
            {
                _censoredPendingSamples++;
                _pending = false;
            }

            try
            {
                if (!IsFinite(fixedDeltaTime) || fixedDeltaTime <= 0f ||
                    !IsFinite(footBody.angularVelocity) || !IsFinite(footBody.rotation) ||
                    !IsFinite(angularTransportTorqueWorld) || !IsFinite(anklePdTorqueWorld) || !IsFinite(supportAngularTorqueWorld))
                {
                    Invalidate("NON_FINITE_PRE_SOLVE_ANGULAR_INPUT");
                    CopyToReport(report, false);
                    return;
                }

                Vector3 preL;
                if (!TryWorldAngularMomentum(footBody, footBody.angularVelocity, out preL,
                    out Vector3 preInertia, out Quaternion prePrincipalWorld))
                {
                    Invalidate("PRE_SOLVE_WORLD_ANGULAR_MOMENTUM_FAILED");
                    CopyToReport(report, false);
                    return;
                }

                Vector3 torque = angularTransportTorqueWorld + anklePdTorqueWorld + supportAngularTorqueWorld;
                Vector3 torqueImpulse = torque * fixedDeltaTime;
                if (!IsFinite(torque) || !IsFinite(torqueImpulse))
                {
                    Invalidate("NON_FINITE_ARL_FOOT_TORQUE_IMPULSE");
                    CopyToReport(report, false);
                    return;
                }

                float boundsRadius = 0f;
                if (footCollider != null)
                {
                    try
                    {
                        boundsRadius = footCollider.bounds.extents.magnitude;
                        if (!IsFinite(boundsRadius) || boundsRadius < 0f) boundsRadius = 0f;
                    }
                    catch
                    {
                        boundsRadius = 0f;
                    }
                }

                _pending = true;
                _preFixed = fixedSequence;
                _dt = fixedDeltaTime;
                _preAngularVelocity = footBody.angularVelocity;
                _preAngularMomentum = preL;
                _preBodyPointer = footBody.Pointer; // managed IL2CPP owner identity, not a new native getter
                _preInertia = preInertia;
                _prePrincipalWorld = prePrincipalWorld;
                CaptureModelParameters(footBody);
                _arlTorqueWorld = torque;
                _arlTorqueImpulse = torqueImpulse;
                _transportTorqueImpulse = angularTransportTorqueWorld * fixedDeltaTime;
                _pdTorqueImpulse = anklePdTorqueWorld * fixedDeltaTime;
                _supportTorqueImpulse = supportAngularTorqueWorld * fixedDeltaTime;
                _footBoundsRadius = boundsRadius;
                _preProbeHits = CountHits(probeSnapshot);
                _preProbeMaxAbsClearance = probeSnapshot.MaxAbsClearanceMeters;
                _preProbeSpread = probeSnapshot.SpreadMeters;
                _pendingProjectedCallbacks = 0;
                _pendingAllCallbacks = 0;
                _pendingCollisionImpulse = Vector3.zero;
                _pendingSignedNormalImpulse = 0f;
                _pendingTangentImpulse = 0f;
                _pendingSupportNormal = Vector3.zero;
                _preSolveSamples++;
            }
            catch (Exception e)
            {
                Invalidate("PRE_SOLVE_EXCEPTION:" + e.GetType().Name);
                _pending = false;
            }
            CopyToReport(report, false);
        }

        private void CaptureModelParameters(Rigidbody footBody)
        {
            _modelParametersAvailable = false;
            _modelUnavailableReason = null;
            _preAngularDrag = _preMaxAngularVelocity = 0f;
            try
            {
                _preAngularDrag = footBody.angularDrag;
                _preMaxAngularVelocity = footBody.maxAngularVelocity;
                _modelParametersAvailable = IsFinite(_preAngularDrag) && _preAngularDrag >= 0f &&
                    IsFinite(_preMaxAngularVelocity) && _preMaxAngularVelocity >= 0f;
                if (!_modelParametersAvailable) _modelUnavailableReason = "NONFINITE_OR_NEGATIVE_PRE_PARAMETER";
            }
            catch (Exception e) { _modelUnavailableReason = "PRE_PARAMETER_READ_EXCEPTION:" + e.GetType().Name; }
            // Optional comparison inputs never invalidate V04250 or its original evidence qualification.
        }

        internal void ObserveCollision(
            bool traceEnabled,
            int collisionPreFixedSequence,
            string phase,
            bool projectionValid,
            Vector3 collisionImpulseWorld,
            Vector3 supportNormalWorld,
            float signedNormalImpulse,
            float tangentImpulse,
            FootAnkleFoundationReport report)
        {
            if (!traceEnabled || !_pending || collisionPreFixedSequence != _preFixed)
            {
                CopyToReport(report, false);
                return;
            }

            _pendingAllCallbacks++;
            if (string.Equals(phase, "EXIT", StringComparison.Ordinal))
            {
                CopyToReport(report, false);
                return;
            }

            if (!projectionValid)
            {
                CopyToReport(report, false);
                return;
            }

            if (!IsFinite(collisionImpulseWorld) || !IsFinite(supportNormalWorld) || !IsFinite(signedNormalImpulse) || !IsFinite(tangentImpulse))
            {
                Invalidate("NON_FINITE_AUTHORIZED_COLLISION_IMPULSE");
                CopyToReport(report, false);
                return;
            }

            _pendingProjectedCallbacks++;
            _pendingCollisionImpulse += collisionImpulseWorld;
            _pendingSignedNormalImpulse += signedNormalImpulse;
            _pendingTangentImpulse += tangentImpulse;
            _pendingSupportNormal = supportNormalWorld;
            CopyToReport(report, false);
        }

        internal void ObserveSettledPreLifecycle(
            bool traceEnabled,
            int fixedSequence,
            float anchorMeters,
            Rigidbody footBody,
            FootAnkleFoundationReport report)
        {
            _lastResolvedValid = false;
            _resolvedSolve = default;
            if (!traceEnabled || !_pending || footBody == null)
            {
                CopyToReport(report, false);
                return;
            }

            // A normal join is N -> N+1. If Unity or the test lifecycle skipped the expected Fixed sequence,
            // preserve the sample as censored rather than inventing a join.
            if (fixedSequence != _preFixed + 1)
            {
                _censoredPendingSamples++;
                _pending = false;
                CopyToReport(report, false);
                return;
            }

            try
            {
                Vector3 postW = footBody.angularVelocity;
                Vector3 postL;
                if (!IsFinite(postW) || !IsFinite(footBody.rotation) || !TryWorldAngularMomentum(footBody, postW, out postL,
                    out Vector3 settledInertia, out Quaternion settledPrincipalWorld))
                {
                    Invalidate("SETTLED_WORLD_ANGULAR_MOMENTUM_FAILED");
                    _pending = false;
                    CopyToReport(report, false);
                    return;
                }

                Vector3 deltaW = postW - _preAngularVelocity;
                Vector3 deltaL = postL - _preAngularMomentum;
                Vector3 residual = deltaL - _arlTorqueImpulse;
                Vector3 collisionImpulse = _pendingCollisionImpulse;
                Vector3 equivalentLever = Vector3.zero;
                Vector3 parallelResidual = Vector3.zero;
                float leverMagnitude = 0f;
                float leverRadiusRatio = 0f;
                float perpendicularFraction = 0f;

                float jSq = collisionImpulse.sqrMagnitude;
                float residualMag = residual.magnitude;
                if (jSq > Epsilon * Epsilon)
                {
                    Vector3 jDir = collisionImpulse / Mathf.Sqrt(jSq);
                    parallelResidual = jDir * Vector3.Dot(residual, jDir);
                    Vector3 perpendicularResidual = residual - parallelResidual;
                    equivalentLever = Vector3.Cross(collisionImpulse, residual) / jSq;
                    leverMagnitude = equivalentLever.magnitude;
                    leverRadiusRatio = _footBoundsRadius > Epsilon ? leverMagnitude / _footBoundsRadius : 0f;
                    perpendicularFraction = residualMag > Epsilon ? Mathf.Clamp01(perpendicularResidual.magnitude / residualMag) : 0f;
                }

                if (!IsFinite(deltaW) || !IsFinite(deltaL) || !IsFinite(residual) || !IsFinite(collisionImpulse) ||
                    !IsFinite(equivalentLever) || !IsFinite(parallelResidual) || !IsFinite(leverMagnitude) ||
                    !IsFinite(leverRadiusRatio) || !IsFinite(perpendicularFraction) || !IsFinite(anchorMeters))
                {
                    Invalidate("NON_FINITE_SETTLED_ANGULAR_ATTRIBUTION");
                    _pending = false;
                    CopyToReport(report, false);
                    return;
                }

                _resolvedSamples++;
                if (_pendingProjectedCallbacks == 0) _noProjectedCallbackSamples++;
                else
                {
                    _matchedProjectedCallbackSamples++;
                    if (_pendingProjectedCallbacks > 1) _multipleProjectedCallbackSamples++;
                }

                float deltaWMag = deltaW.magnitude;
                float deltaLMag = deltaL.magnitude;
                float arlImpulseMag = _arlTorqueImpulse.magnitude;
                float residualMagNow = residual.magnitude;
                float collisionImpulseMag = collisionImpulse.magnitude;
                float parallelResidualMag = parallelResidual.magnitude;

                _deltaWAbsSum += deltaWMag;
                _deltaWAbsMax = Mathf.Max(_deltaWAbsMax, deltaWMag);
                _deltaLAbsSum += deltaLMag;
                _deltaLAbsMax = Mathf.Max(_deltaLAbsMax, deltaLMag);
                _supportImpulseAbsSum += _supportTorqueImpulse.magnitude;
                _supportImpulseAbsMax = Mathf.Max(_supportImpulseAbsMax, _supportTorqueImpulse.magnitude);
                _arlImpulseAbsSum += arlImpulseMag;
                _arlImpulseAbsMax = Mathf.Max(_arlImpulseAbsMax, arlImpulseMag);
                _residualImpulseAbsSum += residualMagNow;
                _residualImpulseAbsMax = Mathf.Max(_residualImpulseAbsMax, residualMagNow);
                _collisionImpulseAbsSum += collisionImpulseMag;
                _collisionImpulseAbsMax = Mathf.Max(_collisionImpulseAbsMax, collisionImpulseMag);
                _parallelResidualAbsSum += parallelResidualMag;
                _parallelResidualAbsMax = Mathf.Max(_parallelResidualAbsMax, parallelResidualMag);
                if (collisionImpulseMag > Epsilon)
                {
                    _equivalentLeverSamples++;
                    _equivalentLeverSum += leverMagnitude;
                    _equivalentLeverMax = Mathf.Max(_equivalentLeverMax, leverMagnitude);
                    _perpendicularExplainableFractionSamples++;
                    _perpendicularExplainableFractionSum += perpendicularFraction;
                }

                _lastResolvedValid = true;
                _lastPreFixed = _preFixed;
                _lastSettledFixed = fixedSequence;
                _lastAnchorMeters = anchorMeters;
                _lastPreW = _preAngularVelocity;
                _lastPostW = postW;
                _lastDeltaW = deltaW;
                _lastDeltaL = deltaL;
                _lastArlTorqueImpulse = _arlTorqueImpulse;
                _lastSupportTorqueImpulse = _supportTorqueImpulse;
                _lastResidualAngularImpulse = residual;
                _lastCollisionImpulse = collisionImpulse;
                _lastEquivalentLever = equivalentLever;
                _lastEquivalentLeverMagnitude = leverMagnitude;
                _lastFootBoundsRadius = _footBoundsRadius;
                _lastEquivalentLeverRadiusRatio = leverRadiusRatio;
                _lastParallelResidualAngularImpulse = parallelResidual;
                _lastPerpendicularExplainableFraction = perpendicularFraction;
                _lastSignedNormalImpulse = _pendingSignedNormalImpulse;
                _lastTangentImpulse = _pendingTangentImpulse;
                _lastProjectedCallbacks = _pendingProjectedCallbacks;
                _lastAllCallbacks = _pendingAllCallbacks;
                _lastPreProbeHits = _preProbeHits;
                _lastPreProbeMaxAbsClearance = _preProbeMaxAbsClearance;
                _lastPreProbeSpread = _preProbeSpread;

                _resolvedSolve = new AngularSolve
                {
                    Resolved = true, PreFixed = _preFixed, SettledFixed = fixedSequence,
                    PreBodyPointer = _preBodyPointer, SettledBodyPointer = footBody.Pointer,
                    Dt = _dt, BoundsRadius = _footBoundsRadius,
                    PreW = _preAngularVelocity, SettledW = postW,
                    PreL = _preAngularMomentum, SettledL = postL,
                    PreInertia = _preInertia, SettledInertia = settledInertia,
                    PrePrincipalWorld = _prePrincipalWorld, SettledPrincipalWorld = settledPrincipalWorld,
                    ModelParametersAvailable = _modelParametersAvailable, ModelUnavailableReason = _modelUnavailableReason,
                    PreAngularDrag = _preAngularDrag, PreMaxAngularVelocity = _preMaxAngularVelocity,
                    TransportJ = _transportTorqueImpulse, PdJ = _pdTorqueImpulse,
                    SupportJ = _supportTorqueImpulse, ArlJ = _arlTorqueImpulse,
                    GroundJ = collisionImpulse, ProjectedCallbacks = _pendingProjectedCallbacks,
                    AllCallbacks = _pendingAllCallbacks
                };

                bool tail = deltaWMag >= TailAngularVelocityDelta || anchorMeters >= TailAnchorMeters;
                if (tail) _tailSamples++;

                if (!_peakInitialized || deltaWMag > _peakDeltaW)
                {
                    _peakInitialized = true;
                    _peakDeltaW = deltaWMag;
                    _peakPreFixed = _preFixed;
                    _peakSettledFixed = fixedSequence;
                    _peakAnchorMeters = anchorMeters;
                    _peakPreW = _preAngularVelocity;
                    _peakPostW = postW;
                    _peakDeltaWVector = deltaW;
                    _peakDeltaL = deltaL;
                    _peakArlTorqueImpulse = _arlTorqueImpulse;
                    _peakSupportTorqueImpulse = _supportTorqueImpulse;
                    _peakResidualAngularImpulse = residual;
                    _peakCollisionImpulse = collisionImpulse;
                    _peakEquivalentLever = equivalentLever;
                    _peakFootBoundsRadius = _footBoundsRadius;
                    _peakLeverRadiusRatio = leverRadiusRatio;
                    _peakParallelResidual = parallelResidual;
                    _peakPerpendicularExplainableFraction = perpendicularFraction;
                    _peakSignedNormalImpulse = _pendingSignedNormalImpulse;
                    _peakTangentImpulse = _pendingTangentImpulse;
                    _peakProjectedCallbacks = _pendingProjectedCallbacks;
                    _peakAllCallbacks = _pendingAllCallbacks;
                    _peakPreProbeHits = _preProbeHits;
                    _peakPreProbeMaxAbsClearance = _preProbeMaxAbsClearance;
                    _peakPreProbeSpread = _preProbeSpread;
                }

                // V04430: tail counters and peak vectors above are retained; long per-tail logging
                // is deferred to existing reports/windows, avoiding string bursts during simulation.

            }
            catch (Exception e)
            {
                Invalidate("SETTLED_EXCEPTION:" + e.GetType().Name);
            }

            _pending = false;
            CopyToReport(report, false);
        }

        internal void CopyToReport(FootAnkleFoundationReport report, bool formatSummaries = true)
        {
            if (report == null) return;
            report.FootAngularImpulseAttributionMode = Mode;
            report.FootAngularImpulseAttributionFinite = _finite;
            report.FootAngularImpulseAttributionInvalidReason = _invalidReason;
            report.FootAngularImpulseAttributionEvidenceReady = EvidenceReady;
            if (!formatSummaries) return;
            report.FootAngularImpulseAttributionCurrentSummary =
                "pending=" + _pending +
                "/preFixed=" + _preFixed +
                "/dt=" + F(_dt) +
                "/callbacks(projected-all)=" + _pendingProjectedCallbacks + "-" + _pendingAllCallbacks +
                "/collisionJ=" + V(_pendingCollisionImpulse) +
                "/supportN=" + V(_pendingSupportNormal) +
                "/arlTorque=" + V(_arlTorqueWorld) +
                "/lastResolved=" + _lastResolvedValid +
                (_lastResolvedValid
                    ? "/last(pre-settled-anchorMm)=" + _lastPreFixed + "-" + _lastSettledFixed + "-" + F(_lastAnchorMeters * 1000f) +
                      "/W(pre-post-delta)=" + V(_lastPreW) + ";" + V(_lastPostW) + ";" + V(_lastDeltaW) +
                      "/angularJ(dL-arl-residual)=" + V(_lastDeltaL) + ";" + V(_lastArlTorqueImpulse) + ";" + V(_lastResidualAngularImpulse) +
                      "/supportAngularJ=" + V(_lastSupportTorqueImpulse) +
                      "/collisionJ=" + V(_lastCollisionImpulse) +
