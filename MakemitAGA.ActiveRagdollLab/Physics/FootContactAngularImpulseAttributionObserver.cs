    /// <summary>
    /// ARL v0.4.25 observer-only attribution for the dynamic Foot angular tail exposed after v0.4.24 removed the
    /// Discrete-collision whole-solve Ground-reaction dropout.
    ///
    /// Important IL2CPP boundary: v0.4.2.1 already proved Collision.GetContact(int) is unavailable on this runtime.
    /// This observer therefore does NOT reintroduce ContactPoint/contactCount reads. Instead it closes the measurable
    /// angular-impulse budget around the exact authorized support callback:
    ///
    ///   pre-solve world angular momentum L0
    ///   + direct ARL Foot torque impulse (angular transport + ankle PD + V04260 support damping)
    ///   + collision aggregate impulse J (read in the authorized callback)
    ///   -> settled Fixed N+1 world angular momentum L1
    ///
    /// The residual angular impulse K = (L1-L0) - J_ARL still contains PhysX contact angular response, Rigidbody
    /// angular-drag integration and solver coupling. When aggregate collision impulse J is non-zero, the minimum-norm
    /// equivalent lever r_eq = (J x K) / |J|^2 is reported. r_eq is NOT asserted to be a real ContactPoint; it only
    /// answers whether the observed non-ARL angular impulse is geometrically compatible with a strongly eccentric
    /// resultant Ground impulse. The component of K parallel to J cannot be generated by r x J and is reported
    /// separately. No force, torque, transform, collider, gravity, material or controller write exists here.
    /// </summary>
    internal sealed class FootContactAngularImpulseAttributionObserver
