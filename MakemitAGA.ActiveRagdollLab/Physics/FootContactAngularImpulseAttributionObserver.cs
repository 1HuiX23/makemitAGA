        private void Invalidate(string reason)
        {
            _finite = false;
            if (string.IsNullOrEmpty(_invalidReason)) _invalidReason = reason;
        }

        private static bool TryWorldAngularMomentum(Rigidbody body, Vector3 worldAngularVelocity, out Vector3 worldAngularMomentum,
            out Vector3 inertia, out Quaternion principalWorld)
        {
            worldAngularMomentum = Vector3.zero;
            inertia = Vector3.zero;
            principalWorld = Quaternion.identity;
            if (body == null || !IsFinite(worldAngularVelocity) || !IsFinite(body.rotation) || !IsFinite(body.inertiaTensor) || !IsFinite(body.inertiaTensorRotation))
                return false;
            inertia = body.inertiaTensor;
            if (inertia.x <= Epsilon || inertia.y <= Epsilon || inertia.z <= Epsilon) return false;
            principalWorld = Normalize(body.rotation * body.inertiaTensorRotation);
            Vector3 wPrincipal = Quaternion.Inverse(principalWorld) * worldAngularVelocity;
            Vector3 lPrincipal = new Vector3(inertia.x * wPrincipal.x, inertia.y * wPrincipal.y, inertia.z * wPrincipal.z);
            worldAngularMomentum = principalWorld * lPrincipal;
            return IsFinite(worldAngularMomentum);
        }

        private static int CountHits(FootSoleProbeSnapshot snapshot)
        {
            int n = 0;
            if (snapshot.Center.Hit) n++;
            if (snapshot.Toe.Hit) n++;
            if (snapshot.Heel.Hit) n++;
            if (snapshot.Left.Hit) n++;
            if (snapshot.Right.Hit) n++;
            return n;
        }

        private static Quaternion Normalize(Quaternion q)
        {
            float mag = Mathf.Sqrt(q.x * q.x + q.y * q.y + q.z * q.z + q.w * q.w);
            if (!IsFinite(mag) || mag <= Epsilon) return Quaternion.identity;
            float inv = 1f / mag;
            return new Quaternion(q.x * inv, q.y * inv, q.z * inv, q.w * inv);
        }

        private static bool IsFinite(float value) => !float.IsNaN(value) && !float.IsInfinity(value);
        private static bool IsFinite(Vector3 value) => IsFinite(value.x) && IsFinite(value.y) && IsFinite(value.z);
        private static bool IsFinite(Quaternion value) => IsFinite(value.x) && IsFinite(value.y) && IsFinite(value.z) && IsFinite(value.w);
        private static string F(float value) => value.ToString("G9", CultureInfo.InvariantCulture);
        private static string V(Vector3 value) => "(" + F(value.x) + "," + F(value.y) + "," + F(value.z) + ")";
